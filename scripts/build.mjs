// Bundle the CLI and the Worker into the skill folder, so a copied
// skills/signal-first/ works on its own with nothing but Node 18+.
//   node scripts/build.mjs           write the bundles
//   node scripts/build.mjs --check   fail if the committed bundles are stale (CI)

import { build } from "esbuild";
import { readFileSync } from "node:fs";

const OUT = "skills/signal-first/scripts";
const check = process.argv.includes("--check");

const targets = [
  { entryPoints: ["src/cli-entry.js"], outfile: `${OUT}/signal-first.mjs`, platform: "node", banner: { js: "#!/usr/bin/env node\n// Generated by scripts/build.mjs from src/. Do not edit." } },
  { entryPoints: ["src/worker.js"], outfile: `${OUT}/worker.mjs`, platform: "neutral", banner: { js: "// Generated by scripts/build.mjs from src/. Do not edit. Cloudflare Worker entry." } },
];

let stale = [];
for (const t of targets) {
  const result = await build({
    ...t,
    bundle: true,
    format: "esm",
    target: "es2022",
    legalComments: "none",
    charset: "utf8",
    write: !check,
    logLevel: "warning",
  });
  if (check) {
    const fresh = result.outputFiles[0].text;
    let current = "";
    try {
      current = readFileSync(t.outfile, "utf8");
    } catch {
      current = "";
    }
    if (fresh !== current) stale.push(t.outfile);
  }
}
if (stale.length) {
  console.error(`stale bundles: ${stale.join(", ")}. Run: npm run build`);
  process.exit(1);
}
console.log(check ? "bundles are up to date" : `wrote ${targets.map((t) => t.outfile).join(", ")}`);
